def test_a_command_runs_directly_where_kern_does_not_serve_it(tmp_path, monkeypatch) -> None:
    script = ROOT / "scripts" / "work_tickets.py"
    monkeypatch.chdir(tmp_path)
    monkeypatch.delenv(se_components.SWITCH)
    # No kern serves the directory: direct, and with SE_KERN=on a refusal.
    assert se_components.routed(script, ["status"], [], True) is None
    monkeypatch.setenv(se_components.SWITCH, "on")
    assert se_components.routed(script, ["status"], [], True) == 1
    # review.py runs directly too, and its commands are batch: never routed.
    assert se_components.routed(ROOT / "scripts" / "review.py", ["brief"], [], False) is None
    # So do retro.py, overhaul.py, timeline.py and deck.py: overhaul.py facts, the one of them
    # that only reads, runs directly where no kern serves the directory, and with SE_KERN=on refuses.
    assert overhaul.INTERACTIVE_COMMANDS == {"facts"}
    assert se_components.routed(ROOT / "scripts" / "overhaul.py", ["facts"], [], True) == 1
    monkeypatch.setenv(se_components.SWITCH, "")
    for name, words in (("overhaul", ["facts"]), ("retro", ["collect"]), ("timeline", []),
                        ("deck", ["build"]), ("se", ["component", "add"])):
        interactive = " ".join(words) in se_components.script(name).INTERACTIVE_COMMANDS
        assert se_components.routed(ROOT / "scripts" / f"{name}.py", words, [], interactive) is None
    monkeypatch.setenv(se_components.SWITCH, "on")
    # A command that writes is never routed; SE_KERN=off routes nothing.
    assert se_components.routed(script, ["init"], [], False) is None
    monkeypatch.setenv(se_components.SWITCH, "off")
    assert se_components.routed(script, ["status"], [], True) is None


