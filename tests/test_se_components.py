def test_the_parser_declares_what_the_command_registry_holds() -> None:
    """Read from the argparse parser, each work_tickets.py command's catalog entry is what its
    registry entry says: the help it was registered with, and the usage of its own arguments alone."""
    catalog = {name: command for d in se_components.catalog(ROOT, GROUPS[:4])
               for name, command in d.commands.items()}
    for words, command in work_tickets.leaf_commands():
        alone = argparse.ArgumentParser(prog=" ".join(("work_tickets.py", *words)), add_help=False)
        work_tickets.add_arguments(alone, command)
        declared = catalog[" ".join(("work_tickets.py", *words))]
        assert declared.help == command.help
        assert declared.usage == se_components.usage(alone.prog, alone)
        assert declared.klass == ("interactive" if " ".join(words) in
                                   work_tickets.INTERACTIVE_COMMANDS else "batch")


def test_any_scripts_parser_declares_its_groups_and_refuses_a_command_in_none() -> None:
    top = argparse.ArgumentParser(prog="tool.py")
    commands = top.add_subparsers(dest="command", required=True)
    commands.add_parser("show", help="show it; and more").add_argument("--all", action="store_true")
    nested = commands.add_parser("set", help="set").add_subparsers(dest="what", required=True)
    nested.add_parser("one", help="set one").add_argument("value")
    groups = [se_components.Group("tool", "Tool", "A tool.", ("show", "set one"))]

    text = se_components.declarations(top, groups, interactive={"show"})["tool"]
    assert text.startswith("# Generated by `work_tickets.py docs` from tool.py's parser;")
    assert '[commands."tool.py show"]\nusage = "tool.py show [--all]"\nsummary = "show it"' in text
    assert '[commands."tool.py set one"]\nusage = "tool.py set one value"' in text
    assert text.count('class = "interactive"') == 1
    with pytest.raises(ValueError, match=r"tool.py: .*missing \['set one'\], unknown \['gone'\]"):
        se_components.declarations(top, [groups[0]._replace(commands=("show", "gone"))])

    # A parser without subcommands is one command, the script itself, named "" in its group.
    bare = argparse.ArgumentParser(prog="page.py", description="Write the page.")
    bare.add_argument("--destination", required=True)
    text = se_components.declarations(bare, [se_components.Group("page", "Page", "A page.", ("",))])["page"]
    assert ('[commands."page.py"]\nusage = "page.py --destination DESTINATION"\n'
            'summary = "Write the page."' in text)


