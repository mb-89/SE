    write_source(tmp_path, "drafts/skills/try/references/more.md", "More.\n")
    (tmp_path / "se.toml").write_text(f'[project]\nversion = "1.0.0"\n[plugin]\n{setting}\n', encoding="utf-8", newline="\n")
    return tmp_path


