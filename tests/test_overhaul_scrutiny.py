"""The overhaul's scrutiny facts (scripts/overhaul_scrutiny.py), through `overhaul.py facts` on the
fixture checkout of tests/test_overhaul.py: the files over the bound with their jobs, the doors, the
spawn marks, the slowest test files, the lines many tests run, and every question's facts."""

from __future__ import annotations

import hygiene
import overhaul
import overhaul_scrutiny
from test_overhaul import APP, checkout, facts, git  # noqa: F401  (checkout: the fixture)

CLOCK_TEST = """\
import time

import pytest


@pytest.mark.spawns("contract: the clock")
def test_clock():
    assert time.time()
"""

SLOW_TEST = """\
import time

import pytest


@pytest.mark.spawns("shell: a shell")
def test_slow():
    time.time()


@pytest.mark.spawns("shell: another")
def test_slower():
    pass
"""

# What the scrutiny reads beside the fixture's code: a reason for its long file, its commands'
# component, a door, two test files with spawn marks, and CI's seconds per test file.
SCRUTINY = {
    "se.toml": '[project]\nauthored_content = ["README.md"]\n\n[long_files]\n'
               '"scripts/app.py" = "the fixture\'s commands, one job each"\n',
    "components/app/component.toml": '# Code generated by work_tickets.py docs from scripts/app.py. DO NOT EDIT.\n'
                                     'name = "app"\n[commands."app.py ship"]\n[commands."app.py forgotten"]\n',
    "scripts/doors/clock.toml": 'door = "clock"\nlevel = "warn"\ncalls = ["time.time"]\n'
                                'contract_tests = ["tests/test_clock.py"]\n',
    "tests/test_clock.py": CLOCK_TEST,
    "tests/test_slow.py": SLOW_TEST,
    "tests/file-seconds.json": '{"tests/test_app.py": 0.5, "tests/test_slow.py": 9.0, "tests/test_clock.py": 0.1}\n',
}


def test_facts_scrutinize_the_long_files_the_doors_the_spawn_marks_and_the_slowest_files(
        checkout, capsys, monkeypatch):
    for name, text in SCRUTINY.items():
        (checkout / name).parent.mkdir(parents=True, exist_ok=True)
        (checkout / name).write_text(text, encoding="utf-8")
    git(checkout, "add", ".")
    git(checkout, "commit", "-q", "-m", "Scrutiny")
    monkeypatch.setattr(hygiene, "LONG_LINES", 30)
    found = facts(checkout, capsys)
    assert found["long_file_jobs"] == [{
        "at": "scripts/app.py", "lines": len(APP.splitlines()), "reason": "the fixture's commands, one job each",
        "components": {"app": ["ship", "forgotten"]},
        "jobs": [{"job": "ship", "commands": 1, "lines": 10}, {"job": "forgotten", "commands": 1, "lines": 0},
                 {"job": "no command", "commands": 0, "lines": 15}]}]
    assert found["doors"] == [{"door": "clock", "level": "warn", "contract_tests": ["tests/test_clock.py"],
                               "reaches": 1, "files": 1}]
    assert found["spawn_marks"] == [{"kind": "shell", "marks": 2, "files": ["tests/test_slow.py"]},
                                    {"kind": "contract", "marks": 1, "files": ["tests/test_clock.py"]}]
    assert [row["file"] for row in found["slowest_files"]] == [
        "tests/test_slow.py", "tests/test_app.py", "tests/test_clock.py"]
    assert found["broad_lines"] is None
    assert overhaul.main(["facts", "--repo", str(checkout)]) == 0
    report = capsys.readouterr().out
    assert (f"- scripts/app.py: {len(APP.splitlines())} lines; the fixture's commands, one job each; commands by "
            "component: app: ship, forgotten; lines per job: ship 10, forgotten 0, no command 15") in report
    assert "- clock (warn): 1 reaches in 1 files outside; contract tests: tests/test_clock.py" in report
    assert "- Which test files are slowest, and what makes them slow? slowest_files" in report
    (checkout / "se.toml").write_text('[project]\nauthored_content = ["README.md"]\n', encoding="utf-8")
    assert facts(checkout, capsys)["long_file_jobs"][0]["reason"] == ""


def test_facts_refuse_a_question_that_names_no_fact(checkout, capsys, monkeypatch):
    monkeypatch.delitem(overhaul_scrutiny.QUESTION_FACTS, "slowest_tests")
    assert overhaul.main(["facts", "--repo", str(checkout)]) == 2
    assert "slowest_tests: the question names no fact" in capsys.readouterr().err
    assert overhaul_scrutiny.question_fact_problems(
        ["doors", "voice", "empty"], {"doors"},
        {"doors": ("doors", "gone"), "voice": " ", "empty": (), "stale": ("doors",)}) == [
        "QUESTION_FACTS['stale']: no question of overhaul-questions; remove the entry",
        "QUESTION_FACTS['doors']: gone is no fact overhaul.py computes",
        "QUESTION_FACTS['voice']: a judgment names its reason",
        "QUESTION_FACTS['empty']: names no fact",
    ]


def test_the_lines_many_tests_run_are_counted_by_file():
    lines = {f"t{number}": frozenset({(1, 1), (1, 2)} | ({(2, 9)} if number < 2 else set())) for number in range(3)}
    assert overhaul_scrutiny.broad_lines(lines, {1: "scripts/app.py"}, top=10, broad=2) == [
        {"file": "scripts/app.py", "lines": 2, "most": 3}, {"file": "2", "lines": 1, "most": 2}]
