package issues

import "testing"

// What se prints of an issue's text, recorded for each case.
func TestShownLeavesOutMarksAndTheFooter(t *testing.T) {
	t.Parallel()
	for _, c := range []struct{ name, body, want string }{
		{"plain", "do it\n\nwell", "do it\n\nwell"},
		{"the new mark and a footer", "do it\n\n<!-- se:new -->\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_", "do it"},
		{"a PR's footer and its session", "did it\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\nhttps://claude.ai/code/session_1", "did it"},
		{"a mark over lines", "<!-- se:review {\"a\":\n1} -->\nfound\r\n<!-- se:box s1 -->", "found"},
		{"a skills line", "do it\n\nSkills: work <!-- se:skills -->", "do it\n\nSkills: work"},
		{"a footer named in a sentence stays", "It says Generated by [Claude Code](u) in the middle.", "It says Generated by [Claude Code](u) in the middle."},
		{"only marks", "<!-- se:resume -->", ""},
	} {
		if got := Shown(c.body); got != c.want {
			t.Errorf("%s: %q, want %q", c.name, got, c.want)
		}
	}
}

func TestBrieflyHoldsBothCadencesInOneLine(t *testing.T) {
	t.Parallel()
	cads := []Cadence{{Kind: "retro", Every: 10, Closed: 3}, {Kind: "overhaul", Every: 5, Closed: 5, Previous: 2}}
	if got, want := Briefly(cads), "Cadence: retro at 3 of 10; overhaul due (5 of 5)."; got != want {
		t.Errorf("%q, want %q", got, want)
	}
	if got, want := Briefly([]Cadence{{Kind: "retro", Every: 10, Closed: 12, Open: 7}}), "Cadence: retro #7 open."; got != want {
		t.Errorf("%q, want %q", got, want)
	}
	if Briefly(nil) != "" {
		t.Error("no cadence is no line")
	}
}
