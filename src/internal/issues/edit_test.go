// Internal test package: it reads the fake GitHub back through api.
package issues

import (
	"reflect"
	"strings"
	"testing"
)

// editing is GitHub with se issue 5, a retro sub-issue of 1 with its mark and
// skills line, #6 its sibling titled "Taken", #7 a hand-made issue, and #8
// whose body lost its mark to an edit by hand.
func editing(t *testing.T) Source {
	t.Helper()
	gh := recorded(t, map[string]string{
		"repos/o/r/issues?labels=se&state=open&per_page=100": `[
			{"number":1,"title":"Parent","state":"open","sub_issues_summary":{"total":2}},
			{"number":5,"title":"Do it","state":"open"},
			{"number":6,"title":"Taken","state":"open"}]`,
		"repos/o/r/issues/1":                         `{"id":101,"number":1,"state":"open","title":"Parent","labels":[{"name":"se"}]}`,
		"repos/o/r/issues/1/sub_issues?per_page=100": `[{"number":5,"state":"open"},{"number":6,"state":"open"}]`,
		"repos/o/r/issues/5":                         `{"id":505,"number":5,"state":"open","title":"Do it","body":"The task.\n\n<!-- se:retro unattended -->\n\nSkills: retro <!-- se:skills -->\n\n<!-- se:new -->","labels":[{"name":"se"}]}`,
		"repos/o/r/issues/6":                         `{"id":606,"number":6,"state":"open","title":"Taken","body":"x\n\n<!-- se:new -->","labels":[{"name":"se"}]}`,
		"repos/o/r/issues/7":                         `{"id":707,"number":7,"state":"open","title":"By hand","body":"y"}`,
		"repos/o/r/issues/8":                         `{"id":808,"number":8,"state":"closed","title":"Lost","body":"Sharper.\n\nGenerated by Claude Code","labels":[{"name":"se"}]}`,
	})
	return Source{Proc: machine, Repo: repo, GitHub: gh, Clock: atNow()}
}

func ptr(s string) *string { return &s }

func TestEditRewritesTheBodyKeepingTheMarkAndTheSeBlocks(t *testing.T) {
	t.Parallel()
	s := editing(t)
	ed, err := s.Edit(5, ptr("Do it well"), ptr("The sharper task.\n<!-- se:new -->\n"))
	if err != nil {
		t.Fatal(err)
	}
	want := "The sharper task.\n\n<!-- se:retro unattended -->\n\nSkills: retro <!-- se:skills -->\n\n<!-- se:new -->"
	got := issueAt(t, s.GitHub, 5)
	if got.Title != "Do it well" || got.Body != want || ed.Issue.Number != 5 || ed.Issue.Title != "Do it well" {
		t.Fatalf("%+v %+v", got, ed)
	}
	if !reflect.DeepEqual(ed.Kept, []string{"<!-- se:retro unattended -->", "Skills: retro <!-- se:skills -->"}) {
		t.Fatalf("kept %q", ed.Kept)
	}
}

func TestEditLetsTheNewBodyCarryItsOwnSeBlock(t *testing.T) {
	t.Parallel()
	s := editing(t)
	if _, err := s.Edit(5, nil, ptr("New.\n\nSkills: work <!-- se:skills -->")); err != nil {
		t.Fatal(err)
	}
	want := "New.\n\nSkills: work <!-- se:skills -->\n\n<!-- se:retro unattended -->\n\n<!-- se:new -->"
	if got := issueAt(t, s.GitHub, 5); got.Title != "Do it" || got.Body != want {
		t.Fatalf("%+v", got)
	}
}

func TestEditWithNeitherPutsALostMarkBack(t *testing.T) {
	t.Parallel()
	s := editing(t)
	if _, err := s.Edit(8, nil, nil); err != nil {
		t.Fatal(err)
	}
	if got := issueAt(t, s.GitHub, 8); got.Title != "Lost" || got.Body != "Sharper.\n\nGenerated by Claude Code\n\n<!-- se:new -->" {
		t.Fatalf("%+v", got)
	}
}

func TestEditRefusesWhatSeDoesNotOwnAndABadTitle(t *testing.T) {
	t.Parallel()
	s := editing(t)
	for n, c := range map[int]struct {
		title *string
		want  string
	}{
		7:  {nil, "#7 is not an se issue"},
		99: {nil, "#99 does not exist"},
		5:  {ptr(" "), "needs a --title"},
		6:  {ptr("Do it "), `#5 is an open se issue titled "Do it"`},
	} {
		if _, err := s.Edit(n, c.title, nil); err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("#%d: %v, want %q", n, err, c.want)
		}
	}
	if w := s.GitHub.(interface{ Writes() []string }).Writes(); len(w) != 0 {
		t.Fatalf("wrote %q", w)
	}
	// Its own title, spaces aside, is no duplicate.
	if _, err := s.Edit(5, ptr("Do it "), nil); err != nil {
		t.Fatal(err)
	}
}
