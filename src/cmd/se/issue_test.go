// hubAt hands every call a fake GitHub, seeded from recorded answers, until
// the test ends.
func hubAt(t *testing.T, answers map[string]string) *github.Fake {
	t.Helper()
	f := github.NewFake(clock.NewFake(testedAt))
	if err := f.Seed(answers); err != nil {
		t.Fatal(err)
	}
	worldOf(t).GitHub = f
	return f
}

