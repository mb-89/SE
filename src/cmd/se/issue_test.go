func fires(t *testing.T) int { return worldOf(t).Net.(*sehttp.Fake).Fired(routineURL) }

// What a plain pull of recordedIssues says of why #3 is at the top, and of the cadences.
const (
	picked = "The lowest ready issue at the top, a parent: a take coordinates its tree."
	// parentNote is what a pull says of #3, a manifest: it holds no work.
	parentNote = "#3 is a parent: it holds no work. Its agent, se:coordinator, is the box itself: coordinate its tree with se issue pull --in 3 --take"
	cadences   = "1 se issue closed and no retro has closed yet; a retro is due at 10.\n0 retros closed and no overhaul has closed yet; an overhaul is due at 5."
	// marked is #3's body as GitHub holds it: se's marks and the attribution footer around "do it".
	marked = "<!-- se:takeover 1 -->\ndo it\n\n<!-- se:new -->\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
)

func TestIssuePullNamesTheNextReadyIssue(t *testing.T) {
	t.Parallel()
	gh := recordedIssues(t)
	if _, err := gh.Send("PATCH", "repos/o/r/issues/3", github.Field{Name: "body", Value: marked}); err != nil {
		t.Fatal(err)
	}
	patched, asked := len(gh.Writes()), gh.Requests()
	ws := t.TempDir()
	code, out, errs := se(t, "issue", "pull", "--repo", "o/r", "--workspace", ws)
	if code != 0 || out != "#3 three\nu3\n"+picked+"\n"+parentNote+"\n"+cadences+"\n" {
		t.Fatalf("exit %d, %q %q", code, out, errs)
	}
	// The body comes with --full, without se's marks and the attribution footer.
	code, out, errs = se(t, "issue", "pull", "--full", "--repo", "o/r", "--workspace", ws)
	if code != 0 || out != "#3 three\nu3\n"+picked+"\n"+parentNote+"\n\ndo it\n\n"+cadences+"\n" {
		t.Fatalf("exit %d, %q %q", code, out, errs)
	}
	// Without --take, pull only shows the issue: it writes nothing to GitHub,
	// fires nothing and leaves the workspace as it was, but for the ledger
	// of the GitHub requests it made.
	if w := gh.Writes()[patched:]; len(w) != 0 {
		t.Errorf("pull without --take wrote to GitHub: %q", w)
	}
	var left []string
	_ = filepath.WalkDir(ws, func(path string, d fs.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			left = append(left, strings.TrimPrefix(path, ws+string(filepath.Separator)))
		}
		return nil
	})
	if fires(t) != 0 || !slices.Equal(left, []string{filepath.FromSlash(battery.CallsFile), filepath.FromSlash(issues.RequestsFile)}) {
		t.Errorf("pull without --take fired %d times, left %v in the workspace", fires(t), left)
	}
	if n, err := issues.Requests(worldOf(t).Disk, ws); err != nil || n == 0 || n != gh.Requests()-asked {
		t.Errorf("the workspace's ledger records %d GitHub requests (%v), want the %d the pulls made", n, err, gh.Requests()-asked)
	}
	code, out, _ = se(t, "issue", "pull", "--json", "--repo", "o/r")
	var answer struct {
		Ready bool
		Issue struct{ Number int }
	}
	if err := json.Unmarshal([]byte(out), &answer); code != 0 || err != nil || !answer.Ready || answer.Issue.Number != 3 {
		t.Fatalf("exit %d, %q %v", code, out, err)
	}
}

