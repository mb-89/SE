#!/usr/bin/env python3
"""SE's workflows and actions in a project, as generated local copies (README "Workflows").

A workflow names a reusable workflow or action by a line the host reads literally, so a call of SE's
own (`uses: <owner>/<repository>/.github/...@<ref>`) would name SE's home in the project's tracked
files: wrong on a second remote with another owner. Instead SE writes the files a project calls into
the project's own `.github/`, and the project calls them as `uses: ./.github/...`; the work model's
"Neutral workflows" records the decision.

- `SHIPPED`: the files SE ships: the reusable workflows and the actions a project calls.
- `generate`: one copy, pure: SE's file at the pin with a header line naming its source path, the
  pin and how CI reaches SE (`repository_expression`); where the file reaches SE's own checkout (an
  action runs SE's scripts, the battery checks out the kern it runs at), the copy checks out SE at
  the pin instead; a reusable workflow keeps only its `workflow_call` trigger.
- `plan`: what `write` and `check` work from: the files, the pin and SE's location, from the
  arguments, the project's `[modules.se]`, then the copies it holds already; with each action a
  workflow among them calls (`CALLS`), so a project that holds the battery's or the release's copy
  gets the action `kern-at-pin` beside it.

`se_workflows.py write [--root <project>] [<path>...]` writes the copies (default: those the project
holds); `se_workflows.py check [--root <project>]` fails where a copy differs from what the pin
generates or an action a held workflow calls is missing, naming the file and the remedy, and where
a workflow's call of the `suite-time` action runs another number of shards than `se.toml` `[tests]
shards` (`shard_mismatches`), naming both files and both numbers. `se_modules.py update se` regenerates them at the new pin.
Exit code 0, 1 findings, 2 a refusal naming its remedy.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

import git_door
import se_home

SE_ROOT = Path(__file__).resolve().parents[1]
MODULE = "se"

# The files a project calls, each by `uses: ./<path>` (an action by its folder).
SHIPPED = (
    ".github/workflows/branch-cleanup.yml",
    ".github/workflows/kern-battery.yml",
    ".github/workflows/kern-release.yml",
    ".github/workflows/release.yml",
    ".github/actions/integrator-pass/action.yml",
    ".github/actions/kern-at-pin/action.yml",
    ".github/actions/suite-shard/action.yml",
    ".github/actions/suite-time/action.yml",
)

# The action each workflow calls by `uses: ./.github/actions/<name>`, so a project that holds the
# workflow's copy holds the action's beside it: `plan` adds it where the pin ships it, and `check`
# names one missing.
CALLS = {
    ".github/workflows/kern-battery.yml": ".github/actions/kern-at-pin/action.yml",
    ".github/workflows/kern-release.yml": ".github/actions/kern-at-pin/action.yml",
}

MARKER = "# se-workflows:"
HEADER = re.compile(r"^# se-workflows: (?P<path>\S+) at (?P<ref>[0-9a-f]{40}) from (?P<repository>\S.*)$")
NOTE = ("# Generated by SE from its file of that path at that commit; do not edit: "
        "se_workflows.py write regenerates it (SE's README \"Workflows\").\n")
OWNER = "${{ github.repository_owner }}"
SHA = re.compile(r"^[0-9a-f]{40}$")

# Where SE's own file reaches SE's checkout, and what the copy reaches instead.
ACTION_SCRIPTS = '"$GITHUB_ACTION_PATH/../../../scripts/'
CHECKOUT = ".se/ci/se"
COPY_SCRIPTS = f'"$GITHUB_WORKSPACE/{CHECKOUT}/scripts/'
WORKFLOW_REPOSITORY = "${{ job.workflow_repository }}"
WORKFLOW_SHA = "${{ job.workflow_sha }}"


class WorkflowError(Exception):
    """A refusal that names its remedy."""


def repository_expression(url: str) -> str:
    """How CI reaches SE, from a module URL: `../<name>.git`, the repository beside the project,
    is `${{ github.repository_owner }}/<name>`; an absolute URL is its `<owner>/<name>`."""
    if se_home.is_relative(url):
        match = re.fullmatch(r"\.\./([\w.-]+?)(?:\.git)?/?", url)
        if match is None:
            raise WorkflowError(f"{url}: a relative SE URL reaches CI only as ../<name>.git, the "
                                "repository beside the project")
        return f"{OWNER}/{match[1]}"
    found = se_home.parse(url)
    if found is None:
        raise WorkflowError(f"{url}: no https or ssh repository URL, so CI cannot reach SE by it")
    return found.tracker


def header(path: str, ref: str, repository: str) -> str:
    return f"{MARKER} {path} at {ref} from {repository}\n{NOTE}"


def read_header(text: str) -> tuple[str, str, str] | None:
    """(path, ref, repository) of a generated copy's first line; None for any other file."""
    match = HEADER.match(text.split("\n", 1)[0])
    return (match["path"], match["ref"], match["repository"]) if match else None


def only_workflow_call(text: str, path: str) -> str:
    """A reusable workflow's text with only its `workflow_call` trigger: a project calls it and
    never runs it on SE's own events."""
    lines = text.splitlines(keepends=True)
    start = next((i for i, line in enumerate(lines) if line.rstrip() == "on:"), None)
    if start is None:
        raise WorkflowError(f"{path}: no `on:` block; SE ships only reusable workflows")
    end = next((i for i in range(start + 1, len(lines))
                if lines[i].strip() and not lines[i][0].isspace()), len(lines))
    kept, keep = [], False
    for line in lines[start + 1:end]:
        if re.match(r"^  [^\s#]", line):
            keep = line.startswith("  workflow_call:")
        if keep and not re.match(r"^  #", line):
            kept.append(line)
    if not kept:
        raise WorkflowError(f"{path}: no workflow_call trigger; SE ships only reusable workflows")
    while not kept[-1].strip():
        kept.pop()
    return "".join(lines[:start + 1] + kept + ["\n"] + lines[end:])


def checkout_step(repository: str, ref: str, indent: str) -> str:
    return (f"{indent}- name: SE at the project's pin\n"
            f"{indent}  uses: actions/checkout@v7\n"
            f"{indent}  with:\n"
            f"{indent}    repository: {repository}\n"
            f"{indent}    ref: {ref}\n"
            f"{indent}    path: {CHECKOUT}\n")


def generate(text: str, path: str, ref: str, repository: str) -> str:
    """The project's copy of SE's file `path` at commit `ref`, reaching SE as `repository`."""
    if path not in SHIPPED:
        raise WorkflowError(f"{path}: SE ships no such file; it ships {', '.join(SHIPPED)}")
    if not SHA.match(ref):
        raise WorkflowError(f"{ref}: the pin is a full commit SHA")
    body = text.replace(WORKFLOW_REPOSITORY, repository).replace(WORKFLOW_SHA, ref)
    if path.startswith(".github/workflows/"):
        body = only_workflow_call(body, path)
    elif ACTION_SCRIPTS in body:
        steps = re.search(r"(?m)^  steps:\n(?P<indent> +)- ", body)
        if steps is None:
            raise WorkflowError(f"{path}: an action that runs SE's scripts has no composite steps")
        at = steps.start("indent")
        body = (body[:at] + checkout_step(repository, ref, steps["indent"]) + body[at:]).replace(
            ACTION_SCRIPTS, COPY_SCRIPTS)
    return header(path, ref, repository) + body


# The wiring: the project's files, its se.toml and SE's git.


@dataclass(frozen=True)
class Plan:
    """What `write` and `check` work from: the files, the pin and SE's location, and SE's checkout
    that holds the pin."""

    paths: tuple[str, ...]
    ref: str
    repository: str
    source: Path


def held(root: Path) -> dict[str, tuple[str, str, str]]:
    """The generated copies the project holds, by path, with their headers."""
    found = {}
    for path in SHIPPED:
        file = root / path
        if file.is_file() and (seen := read_header(file.read_text(encoding="utf-8"))) is not None:
            found[path] = seen
    return found


def module_table(root: Path) -> dict | None:
    manifest = root / "se.toml"
    if not manifest.is_file():
        return None
    with manifest.open("rb") as handle:
        table = tomllib.load(handle).get("modules", {}).get(MODULE)
    return table if isinstance(table, dict) else None


def commit(source: Path, ref: str) -> str:
    done = git_door.run("rev-parse", "--verify", "-q", f"{ref}^{{commit}}", root=source)
    if done.returncode != 0:
        raise WorkflowError(f"{source} has no commit {ref}: run se_modules.py sync, or name an SE "
                            "checkout that has it with --source")
    return done.stdout.strip()


def plan(root: Path, paths: list[str], ref: str | None = None, repository: str | None = None,
         source: Path | None = None) -> Plan:
    """The plan from the arguments, else the project's `[modules.se]`, else the copies it holds."""
    copies = held(root)
    table = module_table(root)
    module = None
    if table is not None:
        import se_modules
        try:
            module = {m.name: m for m in se_modules.load_manifest(root)}[MODULE]
        except se_modules.ModuleError as error:
            raise WorkflowError(str(error)) from error
        if not module.ref:
            raise WorkflowError(f"SE's version range in {root / 'se.toml'} is not locked yet: run "
                                "se_modules.py sync")
        local = se_modules.load_local(se_modules.default_local_config())
        if source is None:
            source = se_modules.resolve(root, module, local).checkout
    pins = {seen[1] for seen in copies.values()}
    places = {seen[2] for seen in copies.values()}
    ref = ref or (module.ref if module else None) or (pins.pop() if len(pins) == 1 else None)
    if ref is None:
        raise WorkflowError(f"no pin for SE's files in {root}: pin SE as [modules.se] in se.toml, or "
                            "name it with --ref" + (" (the copies name more than one)" if pins else ""))
    url = str(table.get("url", "")) if table is not None else ""
    if repository is None:
        if se_home.is_relative(url) or se_home.parse(url) is not None:
            repository = repository_expression(url)
        elif len(places) == 1:
            repository = places.pop()
        else:
            raise WorkflowError(f"no SE location for {root}: pin SE as [modules.se] in se.toml, or "
                                "name it with --repository")
    chosen = tuple(paths) or tuple(copies)
    if not chosen:
        raise WorkflowError(f"{root} holds no copy of SE's files; name the ones it calls: "
                            f"{', '.join(SHIPPED)}")
    unknown = [path for path in chosen if path not in SHIPPED]
    if unknown:
        raise WorkflowError(f"SE ships no {', '.join(unknown)}; it ships {', '.join(SHIPPED)}")
    source = source or SE_ROOT
    pin = commit(source, ref)
    return Plan(with_calls(chosen, source, pin), pin, repository, source)


def with_calls(paths: tuple[str, ...], source: Path, pin: str) -> tuple[str, ...]:
    """`paths` and each action one of them calls (`CALLS`) where SE at `pin` ships it."""
    called = [CALLS[path] for path in paths if path in CALLS]
    return tuple(dict.fromkeys([*paths, *(action for action in called if action not in paths
                                           and git_door.run("cat-file", "-e", f"{pin}:{action}",
                                                            root=source).returncode == 0)]))


def expected(plan: Plan, path: str) -> str:
    done = git_door.run("show", f"{plan.ref}:{path}", root=plan.source)
    if done.returncode != 0:
        raise WorkflowError(f"SE at {plan.ref[:12]} has no {path}: name the files it ships at that pin")
    return generate(done.stdout, path, plan.ref, plan.repository)


def write(root: Path, plan: Plan) -> list[str]:
    """Write each copy of `plan`; one line per file written."""
    report = []
    for path in plan.paths:
        text = expected(plan, path)
        target = root / path
        if target.is_file() and target.read_text(encoding="utf-8") == text:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(text.encode("utf-8"))
        report.append(f"{path}: generated from SE at {plan.ref[:12]}")
    return report


def check(root: Path, plan: Plan) -> list[str]:
    """Each copy of `plan` that differs from what its pin generates, with the remedy, then each call
    of `suite-time` whose shards differ from `se.toml`'s (`shard_mismatches`)."""
    findings = []
    for path in plan.paths:
        callers = [workflow for workflow, action in CALLS.items() if action == path and (root / workflow).is_file()]
        if not (root / path).is_file() and callers:
            findings.append(f"{path}: missing, though {' and '.join(callers)} calls it; run se_workflows.py write")
        elif not (root / path).is_file() or (root / path).read_text(encoding="utf-8") != expected(plan, path):
            findings.append(f"{path}: differs from SE's file at the pin {plan.ref[:12]}; run se_workflows.py write")
    return findings + shard_mismatches(root)


# The shards CI runs and the shards se.toml budgets for (README "Test budget").

SUITE_TIME = "./.github/actions/suite-time"
USES = re.compile(r"^(?P<indent> *)(?:- )?uses: *['\"]?(?P<target>[^'\"\s#]+)")
SHARDS = re.compile(r"^ *shards: *['\"]?(?P<value>[^'\"\s#]+)")


def budget_shards(root: Path) -> tuple[int, bool] | None:
    """`se.toml` `[tests] shards` and whether it is set; None where it is no whole number of 1 or
    more, which the suite's own budget refuses."""
    manifest = root / "se.toml"
    tests = {}
    if manifest.is_file():
        with manifest.open("rb") as handle:
            tests = tomllib.load(handle).get("tests", {})
    tests = tests if isinstance(tests, dict) else {}
    shards = tests.get("shards", 1)
    if isinstance(shards, bool) or not isinstance(shards, int) or shards < 1:
        return None
    return shards, "shards" in tests


def suite_time_shards(text: str) -> list[tuple[int, int]]:
    """(line, shards) of each step of a workflow that calls the `suite-time` action with a literal
    number of shards; an expression (`${{ ... }}`) is the run's and is not compared."""
    lines = text.splitlines()
    found = []
    for at, line in enumerate(lines):
        match = USES.match(line)
        if match is None or match["target"].rstrip("/") != SUITE_TIME:
            continue
        step = len(match["indent"]) if line.lstrip().startswith("- ") else len(match["indent"]) - 2
        start = at
        while start > 0 and not lines[start].lstrip().startswith("- ") and lines[start].strip():
            start -= 1  # the step's own `- ` line, where `uses` is not its first key
        end = at + 1
        while end < len(lines) and (not lines[end].strip()
                                    or len(lines[end]) - len(lines[end].lstrip()) > step):
            end += 1
        for number in range(start, end):
            shards = SHARDS.match(lines[number])
            if shards is not None and shards["value"].isdigit():
                found.append((number + 1, int(shards["value"])))
    return found


def shard_mismatches(root: Path) -> list[str]:
    """Each call of the `suite-time` action in the project's workflows whose `shards:` differs from
    `se.toml` `[tests] shards` (default 1), naming both files and both numbers."""
    budget = budget_shards(root)
    folder = root / ".github" / "workflows"
    if budget is None or not folder.is_dir():
        return []
    shards, set_here = budget
    setting = f"se.toml [tests] shards = {shards}" if set_here else "se.toml [tests] shards is unset (1)"
    findings = []
    for file in sorted(folder.iterdir()):
        if file.suffix not in (".yml", ".yaml") or not file.is_file():
            continue
        for line, ran in suite_time_shards(file.read_text(encoding="utf-8")):
            if ran != shards:
                findings.append(f".github/workflows/{file.name}:{line}: suite-time runs shards: {ran}, "
                                f"but {setting}; make them agree, as the budget is each shard's")
    return findings


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="se_workflows.py", description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=Path.cwd(), help="the project (default: here)")
    parser.add_argument("--source", type=Path, help="the SE checkout holding the pin (default: the "
                        "project's se module, else this SE)")
    parser.add_argument("--ref", help="the pin (default: [modules.se], else the copies' own)")
    parser.add_argument("--repository", help="how CI reaches SE (default: from [modules.se]'s url, "
                        "else the copies' own)")
    commands = parser.add_subparsers(dest="command", required=True)
    writing = commands.add_parser("write", help="write the copies at the pin")
    writing.add_argument("paths", nargs="*", help=f"files to write (default: those held); of {', '.join(SHIPPED)}")
    commands.add_parser("check", help="fail where a copy differs from what the pin generates, or "
                        "suite-time's shards from se.toml's")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        found = plan(root, getattr(args, "paths", []), args.ref, args.repository, args.source)
        if args.command == "write":
            for line in write(root, found) or [f"se_workflows: the copies in {root} are current"]:
                print(line)
            return 0
        findings = check(root, found)
    except WorkflowError as error:
        print(f"se_workflows: {error}", file=sys.stderr)
        return 2
    for line in findings:
        print(f"se_workflows: {line}")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
